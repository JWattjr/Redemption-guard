type Client = ReturnType<typeof makeClients>["client"];

/**
 * Studio Next rejects zero-fee transactions. Prefer a simulation-backed
 * estimate for writes (measures real execution), falling back to the network
 * default policy when the simulation itself reverts (e.g. a blocked request).
 */
export async function feesFor(
  client: Client,
  call?: { address: Hex; functionName: string; args: (string | number | bigint)[] },
): Promise<{ distribution: unknown; feeValue: bigint }> {
  if (call) {
    try {
      const est = await withRetry("estimateTransactionFeesForWrite", () => client.estimateTransactionFeesForWrite({ ...call }), 4);
      return { distribution: est.distribution, feeValue: est.feeValue };
    } catch (err) {
      console.log(`  (simulation estimate unavailable for ${call.functionName}: ${String(err).slice(0, 120)}; using network default)`);
    }
  }
  const est = await withRetry("estimateTransactionFees", () => client.estimateTransactionFees());
  return { distribution: est.distribution, feeValue: est.feeValue };
}

export async function write(
  client: Client,
  address: Hex,
  functionName: string,
  args: (string | number | bigint)[],
  label: string,
  opts: { simulateFees?: boolean } = {},
): Promise<TxOutcome> {
  const fees = await feesFor(client, opts.simulateFees === false ? undefined : { address, functionName, args });
  const hash = (await withRetry(`write ${functionName}`, () =>
    client.writeContract({ address, functionName, args, fees: fees as never }),
  )) as Hex;
  return waitOutcome(client, hash, label);
}

export const FRONTEND_PROOF_FILE = resolve(ROOT, "frontend", "lib", "proof.generated.json");

/** Compact, public copy of the proof flows for the dashboard's proof panel. */
export function writeFrontendProof(proof: {
  contractAddress: string;
  generatedAt: string;
  flows: { name: string; assetId: string; onChainStatus: string; assessmentId: number; exposureAllowed: boolean; assessTx: TxOutcome; exposureTx: TxOutcome }[];
}): void {
  writeJson(FRONTEND_PROOF_FILE, {
    contractAddress: proof.contractAddress,
    generatedAt: proof.generatedAt,
    flows: proof.flows.map((f) => ({
      name: f.name,
      assetId: f.assetId,
      status: f.onChainStatus,
      assessmentId: f.assessmentId,
      exposureAllowed: f.exposureAllowed,
      assess: { hash: f.assessTx.hash, statusName: f.assessTx.statusName, executionResultName: f.assessTx.executionResultName, validators: f.assessTx.validators, votes: f.assessTx.votes },
      exposure: { hash: f.exposureTx.hash, statusName: f.exposureTx.statusName, executionResultName: f.exposureTx.executionResultName, errorText: f.exposureTx.errorText },
    })),
  });
}
