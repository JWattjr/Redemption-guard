export type Hex = `0x${string}`;

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

/**
 * Studio Next rate-limits each client to 30 RPC requests per minute. A
 * rate-limited request is rejected before processing, so retrying is safe.
 */
export async function withRetry<T>(label: string, fn: () => Promise<T>, attempts = 8): Promise<T> {
  for (let i = 1; ; i++) {
    try {
      return await fn();
    } catch (err) {
      const text = err instanceof Error ? `${err.message} ${String((err as { details?: string }).details ?? "")}` : String(err);
      if (i >= attempts || !/rate limit|429|too many requests/i.test(text)) throw err;
      const wait = 15_000 * i;
      console.log(`  (rate limited during ${label}; retrying in ${wait / 1000}s)`);
      await sleep(wait);
    }
  }
}

export function explorerTx(hash: string): string {
  return `${EXPLORER_URL}/tx/${hash}`;
}

